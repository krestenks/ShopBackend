package asterisk

import ShopTelephonyConfig
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.Paths
import java.nio.file.StandardCopyOption

/**
 * Writes [content] to [target] atomically: write a temp file in the same directory,
 * then rename over the target. Prevents Asterisk from ever reading a half-written config.
 */
internal fun writeAtomically(target: Path, content: String) {
    Files.createDirectories(target.parent)
    val tmp = Files.createTempFile(target.parent, target.fileName.toString(), ".tmp")
    try {
        Files.writeString(tmp, content)
        makeWorldReadable(tmp)
        Files.move(tmp, target, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE)
    } finally {
        Files.deleteIfExists(tmp)
    }
}

/**
 * createTempFile defaults to mode 600, which the rename preserves — leaving the
 * asterisk user unable to read the result. An unreadable quectel_shops.conf is
 * fatal: the failed #include makes chan_quectel's config load return null and
 * the driver segfaults (observed on the phone server). Force 644.
 */
internal fun makeWorldReadable(file: Path) {
    try {
        Files.setPosixFilePermissions(file, java.nio.file.attribute.PosixFilePermissions.fromString("rw-r--r--"))
    } catch (_: UnsupportedOperationException) {
        // Non-POSIX filesystem (Windows dev machine) — irrelevant there.
    }
}

private const val GENERATED_HEADER =
    ";; GENERATED by ShopBackend — do not edit by hand; changes are overwritten on provisioning.\n"

/**
 * Owns quectel_shops.conf: one chan_quectel (RoEdAl fork) trunk section per shop,
 * regenerated wholesale from the DB on every provisioning run.
 *
 * Server prerequisite (one-time): /etc/asterisk/quectel.conf must contain
 *   #include quectel_shops.conf
 */
/**
 * Outcome of a trunk-config write. [skippedNoAudio] holds the shops whose modem exposed no ALSA
 * capture device, so no usable trunk could be written for them — the caller needs this to avoid
 * reporting a bring-up as successful when it produced nothing. See [QuectelConfigWriter.regenerate].
 */
data class TrunkWriteResult(val written: List<Int>, val skippedNoAudio: List<Int>)

class QuectelConfigWriter(private val config: AsteriskConfig, private val amiClient: AmiClient) {

    private val file: Path = Paths.get(config.configPath, "quectel_shops.conf")

    /**
     * Set when the trunk config changed but the reload was withheld because a GSM call was up (or we
     * could not tell). The file on disk is already current; only Asterisk's view is stale.
     * [applyPendingReloadIfIdle] drains this once the box is quiet.
     */
    @Volatile
    var reloadPending: Boolean = false
        private set

    /**
     * Apply a previously deferred chan_quectel reload, but only once no GSM call is up. Safe to call
     * on a timer; a no-op unless a reload is actually owed. Returns true if it reloaded.
     */
    fun applyPendingReloadIfIdle(): Boolean {
        if (!reloadPending) return false
        if (amiClient.anyQuectelCallOrNull() != false) return false
        RecoveryAudit.fired(
            action = "module reload chan_quectel.so (deferred)",
            target = "PBX",
            evidence = "trunk config changed earlier while a call was up; box now idle",
            strength = RecoveryAudit.Evidence.STRONG,
            blast = RecoveryAudit.Blast.PBX,
            ami = amiClient,
            callStateOverride = RecoveryAudit.CallState.IDLE,   // guard proved no GSM call is up
        )
        // Clear BEFORE reloading. If a regenerate() lands while the reload is in flight it sets the
        // flag again and we run once more; clearing afterwards would instead mark that newer config
        // as applied when it never was, leaving a shop silently taking no calls.
        reloadPending = false
        runCatching { amiClient.reloadChanQuectel() }
            .onFailure {
                println("[Asterisk] deferred chan_quectel reload failed: ${it.message}")
                reloadPending = true
                return false
            }
        println("[Asterisk] applied deferred chan_quectel reload (box was idle)")
        return true
    }

    fun regenerate(shops: List<ShopTelephonyConfig>, reload: Boolean = true): TrunkWriteResult {
        val written = mutableListOf<Int>()
        val skipped = mutableListOf<Int>()
        val content = buildString {
            append(GENERATED_HEADER)
            for (shop in shops) {
                val device = shop.modemDataDevice?.trim().orEmpty()
                if (device.isEmpty()) continue

                // This fleet carries voice over UAC (USB audio class) only — we never emit an
                // `audio=` tty — so a trunk with no resolvable ALSA capture device cannot carry a
                // call. Emitting one anyway is worse than emitting nothing: chan_quectel's uac=on
                // path defaults alsadev to DEFAULT_ALSADEV ("hw:Android"), fails to open it, and
                // retries every 15s forever. The shop does nothing at all in that state — not even
                // SMS, because the device never reaches `connected`.
                //
                // uac=off is NOT a usable fallback: it only moves the failure one branch over in
                // pvt_start(), to tty_open("") on the empty audio_tty, which also leaves the device
                // unconnected. No config yields SMS-without-voice on this driver, so skip the shop
                // and say why — a missing trunk with a reason beats a trunk that can never connect.
                val alsaDev = shop.modemAlsaDevice?.trim()?.takeIf { it.isNotBlank() }
                if (alsaDev == null) {
                    skipped += shop.shopId
                    continue
                }

                written += shop.shopId
                appendLine()
                appendLine("[${config.trunkName(shop.shopId)}]")
                appendLine("data=$device")
                // UAC (USB audio class) voice path — validated on the EC25-EUX fleet.
                appendLine("uac=on")
                appendLine("alsadev=$alsaDev")
                appendLine("context=${config.inboundContext(shop.shopId)}")
            }
        }
        // A chan_quectel reload re-inits EVERY trunk on the box, dropping any GSM call in any shop.
        // This runs on every backend start, so before the guard below it was the most reliable way
        // we had of hanging up live calls — a crash-restart was enough (audit finding 4).
        //
        // Two rules, in order of how much they buy:
        //   1. Reload only if the file actually changed. At startup it is byte-identical virtually
        //      always, so this alone removes nearly all of the exposure.
        //   2. Never reload while a GSM call is up — and treat "cannot tell" as "a call is up".
        //
        // "Unchanged" must mean "the RUNNING module already matches", not merely "the file on disk
        // matches". Those differ whenever a reload was deferred and the process restarted before the
        // drain won (reloadPending is in-memory only): the file is current, Asterisk is not, and a
        // pure byte comparison would skip the reload forever — that shop silently takes no calls.
        // So also require every trunk we just wrote to actually exist in the running module.
        val previous = runCatching { if (Files.exists(file)) Files.readString(file) else null }.getOrNull()
        val expectedTrunks = written.map { config.trunkName(it) }.toSet()
        // Tri-state: null means we could not ask (never claim staleness from that, or an AMI blip
        // would reload the fleet). An EMPTY-but-valid answer is not the same thing — "the module has
        // loaded no trunks at all" is the most broken state it can be in, and treating it as
        // "cannot tell" disarmed this check in exactly the scenario the comment above describes.
        val runningTrunks = amiClient.quectelDeviceStatesOrNull()?.keys
        val moduleStale = runningTrunks != null && !runningTrunks.containsAll(expectedTrunks)
        val unchanged = previous == content && !moduleStale
        if (moduleStale && previous == content) {
            println("[Asterisk] quectel_shops.conf unchanged but the running module is missing " +
                "${expectedTrunks - runningTrunks!!} — reloading to catch up")
        }

        writeAtomically(file, content)

        if (reload && !unchanged) {
            val anyCall = amiClient.anyQuectelCallOrNull()
            if (anyCall != false) {
                val why = if (anyCall == null) "could not determine whether a call is live" else "a GSM call is live"
                println("[Asterisk] quectel_shops.conf changed but NOT reloading — $why. " +
                    "The file on disk is current; it applies on the next reload.")
                reloadPending = true
            } else {
                RecoveryAudit.fired(
                    action = "module reload chan_quectel.so",
                    target = "PBX",
                    evidence = "quectel_shops.conf content changed (${written.size} trunk(s)); no Quectel channel up",
                    strength = RecoveryAudit.Evidence.STRONG,
                    blast = RecoveryAudit.Blast.PBX,
                    ami = amiClient,
                    // The guard above proved no GSM channel is up, which is the only kind this
                    // action can damage; a PJSIP call being up is not a violation.
                    callStateOverride = RecoveryAudit.CallState.IDLE,
                )
                amiClient.reloadChanQuectel()
                reloadPending = false
            }
        } else if (reload) {
            println("[Asterisk] quectel_shops.conf unchanged — skipping chan_quectel reload")
        }
        println("[Asterisk] Wrote $file (${shops.size - skipped.size} trunk(s))")
        for (sid in skipped) {
            System.err.println(
                "[Asterisk] shop $sid NOT provisioned: its modem exposes no ALSA capture device, so " +
                "it can neither take calls nor send SMS. The modem's USB audio class is most likely " +
                "disabled in firmware — check AT+QCFG=\"usbcfg\" (the trailing field must be 1, not " +
                "0). Fix with AT+QCFG=\"usbcfg\",0x2C7C,0x0125,1,1,1,1,1,0,1 then AT+CFUN=1,1 to " +
                "reboot the modem, and re-provision once the new card appears in /proc/asound/cards."
            )
        }
        return TrunkWriteResult(written = written, skippedNoAudio = skipped)
    }
}

/**
 * Owns extensions_shops.conf: per-shop inbound (GSM → app, GSM SMS → backend) and
 * outbound (app SIP → GSM) dialplan contexts, regenerated wholesale from the DB.
 *
 * Server prerequisites (one-time):
 *   - /etc/asterisk/extensions.conf must contain: #include extensions_shops.conf
 *   - func_curl and JSON_DECODE (res_json / func_json) must be loaded (used to hand
 *     inbound events to the backend over localhost HTTP).
 */
class DialplanWriter(private val config: AsteriskConfig, private val amiClient: AmiClient) {

    private val file: Path = Paths.get(config.configPath, "extensions_shops.conf")

    fun regenerate(
        shops: List<ShopTelephonyConfig>,
        internal: List<InternalShopEntry> = emptyList(),
        managers: List<ManagerDialEntry> = emptyList(),
        reload: Boolean = true,
    ) {
        val d = "$"  // avoids Kotlin template/Asterisk ${...} collisions below
        val content = buildString {
            append(GENERATED_HEADER)
            for (shop in shops) {
                if (shop.modemDataDevice.isNullOrBlank()) continue
                val id = shop.shopId
                val trunk = config.trunkName(id)
                val endpoint = config.endpointId(id)
                val base = config.backendBaseUrl
                val secret = config.internalSecret

                appendLine()
                val p = config.promptsPath
                appendLine("[${config.inboundContext(id)}]")
                appendLine("; Inbound GSM call. The backend call/inbound endpoint logs the call and returns a")
                appendLine("; routing verdict: reject | ring | menu_open | menu_closed | menu_temp.")
                appendLine(";   reject      blacklisted caller, or unknown caller while closed  -> hang up (cause 21)")
                appendLine(";   ring        unknown caller while open                           -> ring the app, no prompts")
                appendLine(";   menu_*      known customer                                      -> welcome + DTMF menu")
                appendLine("exten => s,1,NoOp(Inbound call for shop $id from $d{CALLERID(num)})")
                appendLine(" same => n,Set(SHOP_ID=$id)")
                appendLine(" same => n,Set(VERDICT=$d{CURL($base/api/internal/telephony/call/inbound,secret=$secret&shopId=$id&from=$d{URIENCODE($d{CALLERID(num)})}&uniqueid=$d{UNIQUEID})})")
                appendLine(" same => n,GotoIf($d[\"$d{VERDICT}\" = \"reject\"]?rejected,1)")
                appendLine(" same => n,GotoIf($d[\"$d{VERDICT}\" = \"menu_open\"]?welcomeopen,1)")
                appendLine(" same => n,GotoIf($d[\"$d{VERDICT}\" = \"menu_closed\"]?welcomeclosed,1)")
                appendLine(" same => n,GotoIf($d[\"$d{VERDICT}\" = \"menu_temp\"]?welcometemp,1)")
                appendLine(" same => n,Wait(2)")
                appendLine("; Duty-aware pool routing: backend returns the &-joined on-duty manager")
                appendLine("; endpoints; empty result falls back to this shop's legacy manager endpoint.")
                appendLine(" same => n,Set(TARGETS=$d{CURL($base/api/internal/telephony/call/dial-targets,secret=$secret&shopId=$id)})")
                appendLine(" same => n,ExecIf($d[\"$d{TARGETS}\" = \"\"]?Set(TARGETS=PJSIP/$endpoint))")
                appendLine(" same => n,Dial($d{TARGETS},30)")
                appendLine(" same => n,Hangup()")
                appendLine()
                appendLine("exten => rejected,1,Hangup(21)")
                appendLine()
                appendLine("; Known customer: answer, play the shop's welcome, then run the DTMF menu.")
                appendLine("exten => welcomeopen,1,Answer()")
                appendLine(" same => n,Wait(1)")
                appendLine(" same => n,Playback($p/shop$id-welcome-open)")
                appendLine(" same => n,Goto(menuopen,1)")
                appendLine("exten => welcomeclosed,1,Answer()")
                appendLine(" same => n,Wait(1)")
                appendLine(" same => n,Playback($p/shop$id-welcome-closed)")
                appendLine(" same => n,Goto(menuclosed,1)")
                appendLine("; Temporary operator closure during open hours: open welcome, closed menu (no operator option).")
                appendLine("exten => welcometemp,1,Answer()")
                appendLine(" same => n,Wait(1)")
                appendLine(" same => n,Playback($p/shop$id-welcome-open)")
                appendLine(" same => n,Goto(menuclosed,1)")
                appendLine()
                appendLine("; Menu while open: 1 = SMS booking link, 2 = operator (the manager app). 3 attempts.")
                appendLine("exten => menuopen,1,Set(ATTEMPT=1)")
                appendLine(" same => n(prompt),Read(DIGIT,$p/shop$id-menu-open,1,,1,15)")
                appendLine(" same => n,GotoIf($d[\"$d{DIGIT}\" = \"1\"]?smslink,1)")
                appendLine(" same => n,GotoIf($d[\"$d{DIGIT}\" = \"2\"]?operator,1)")
                appendLine(" same => n,Set(ATTEMPT=$d[$d{ATTEMPT} + 1])")
                appendLine(" same => n,GotoIf($d[$d{ATTEMPT} <= 3]?prompt)")
                appendLine(" same => n,Goto(menutimeout,1)")
                appendLine()
                appendLine("; Menu while closed/temp-closed: only 1 = SMS booking link. 3 attempts.")
                appendLine("exten => menuclosed,1,Set(ATTEMPT=1)")
                appendLine(" same => n(prompt),Read(DIGIT,$p/shop$id-menu-closed,1,,1,15)")
                appendLine(" same => n,GotoIf($d[\"$d{DIGIT}\" = \"1\"]?smslink,1)")
                appendLine(" same => n,Set(ATTEMPT=$d[$d{ATTEMPT} + 1])")
                appendLine(" same => n,GotoIf($d[$d{ATTEMPT} <= 3]?prompt)")
                appendLine(" same => n,Goto(menutimeout,1)")
                appendLine()
                appendLine("exten => menutimeout,1,Set(EVT=$d{CURL($base/api/internal/telephony/call/event,secret=$secret&uniqueid=$d{UNIQUEID}&event=menu_timeout)})")
                appendLine(" same => n,Playback($p/menu-invalid-goodbye)")
                appendLine(" same => n,Hangup()")
                appendLine()
                appendLine("; Digit 1: backend creates a booking token and texts the link via this shop's SIM.")
                appendLine("exten => smslink,1,Set(SMSRESULT=$d{CURL($base/api/internal/telephony/booking-link,secret=$secret&shopId=$id&from=$d{URIENCODE($d{CALLERID(num)})}&uniqueid=$d{UNIQUEID})})")
                appendLine(" same => n,GotoIf($d[\"$d{SMSRESULT}\" = \"ok\"]?sent)")
                appendLine(" same => n,Playback($p/sms-failed)")
                appendLine(" same => n,Hangup()")
                appendLine(" same => n(sent),Playback($p/sms-sent)")
                appendLine(" same => n,Hangup()")
                appendLine()
                appendLine("; Digit 2: ring the manager app.")
                appendLine("exten => operator,1,Set(EVT=$d{CURL($base/api/internal/telephony/call/event,secret=$secret&uniqueid=$d{UNIQUEID}&event=operator)})")
                appendLine(" same => n,Set(TARGETS=$d{CURL($base/api/internal/telephony/call/dial-targets,secret=$secret&shopId=$id)})")
                appendLine(" same => n,ExecIf($d[\"$d{TARGETS}\" = \"\"]?Set(TARGETS=PJSIP/$endpoint))")
                appendLine(" same => n,Dial($d{TARGETS},30)")
                appendLine(" same => n,Playback($p/operator-unavailable)")
                appendLine(" same => n,Hangup()")
                appendLine("; Inbound SMS: chan_quectel delivers body as JSON in \${SMS}; forward to backend.")
                appendLine("exten => sms,1,NoOp(Inbound SMS for shop $id from $d{CALLERID(num)})")
                appendLine(" same => n,Set(SMS_BODY=$d{JSON_DECODE(SMS,msg)})")
                appendLine(" same => n,Set(NOTIFY_RESULT=$d{CURL($base/api/internal/telephony/sms/inbound,secret=$secret&shopId=$id&from=$d{URIENCODE($d{CALLERID(num)})}&body=$d{URIENCODE($d{SMS_BODY})})})")
                appendLine(" same => n,Hangup()")
                appendLine("; SMS delivery/status reports. chan_quectel starts the PBX here with the report")
                appendLine("; JSON in \${REPORT}; top-level keys are subject, direction, success, number.")
                appendLine("; This is the ONLY signal that an outbound SMS failed: the AMI send call returns")
                appendLine("; as soon as the driver queues the message, so a send that the network refuses")
                appendLine("; (an out-of-credit SIM being the common case) is otherwise logged as 'sent'.")
                appendLine("; JSON_DECODE reads top-level keys only, so the nested detail goes over as raw JSON.")
                appendLine("exten => report,1,NoOp(SMS status report for shop $id from $d{CALLERID(num)})")
                appendLine(" same => n,Set(R_SUCCESS=$d{JSON_DECODE(REPORT,success)})")
                appendLine(" same => n,Set(R_SUBJECT=$d{JSON_DECODE(REPORT,subject)})")
                appendLine(" same => n,Set(R_NUMBER=$d{JSON_DECODE(REPORT,number)})")
                appendLine(
                    " same => n,Set(R_RESULT=$d{CURL($base/api/internal/telephony/sms/report," +
                        "secret=$secret&shopId=$id&success=$d{URIENCODE($d{R_SUCCESS})}" +
                        "&subject=$d{URIENCODE($d{R_SUBJECT})}&number=$d{URIENCODE($d{R_NUMBER})}" +
                        "&report=$d{URIENCODE($d{REPORT})})})"
                )
                appendLine(" same => n,Hangup()")
                appendLine()
                appendLine("[${config.outboundContext(id)}]")
                appendLine("; Outbound call from the manager app via this shop's SIM. A GSM SIM does")
                appendLine("; one call at a time, so if the trunk is occupied the Dial can't get a")
                appendLine("; channel — report line busy (SIP 486 + busy tone) to the app instead of a")
                appendLine("; silent failure. DIALSTATUS: CHANUNAVAIL/CONGESTION = SIM occupied/no line;")
                appendLine("; BUSY = the called number is busy.")
                appendLine("exten => _+X.,1,Dial(Quectel/$trunk/$d{EXTEN},60)")
                appendLine(" same => n,Goto(afterdial,1)")
                appendLine("exten => _0X.,1,Dial(Quectel/$trunk/$d{EXTEN},60)")
                appendLine(" same => n,Goto(afterdial,1)")
                appendLine("exten => afterdial,1,NoOp(shop$id outbound DIALSTATUS=$d{DIALSTATUS})")
                appendLine(" same => n,ExecIf($d[\"$d{DIALSTATUS}\"=\"CHANUNAVAIL\"|\"$d{DIALSTATUS}\"=\"CONGESTION\"|\"$d{DIALSTATUS}\"=\"BUSY\"]?Busy(3))")
                appendLine(" same => n,Hangup()")
                appendLine("include => ${internalIncludeName(id)}")
            }

            // ── Internal intercom (shop devices ↔ manager), per manager group ──
            val gsmShopIds = shops.filter { !it.modemDataDevice.isNullOrBlank() }.map { it.shopId }.toSet()
            for (entry in internal) {
                val id = entry.shopId

                // Extensions this shop's manager-family can dial (shared include).
                appendLine()
                appendLine("[${internalIncludeName(id)}]")
                appendLine("; Internal extensions for shop $id's manager group (intercom, no GSM).")
                for (sibling in entry.groupShopIds) {
                    appendLine("exten => ${config.shopPhoneExten(sibling)},1,Dial(PJSIP/${config.phoneEndpointId(sibling)},45)")
                    appendLine(" same => n,Hangup()")
                }
                // Manager-to-manager intercom. The app places colleague calls from its
                // shop{id}-manager identity (context from-sip-shop{id}), which includes this
                // block — so mgr{id} must resolve HERE, not only in from-mgr{id}. Every
                // manager covering this shop is dialable; PJSIP/mgr{id} exists via
                // ensureAllManagerEndpoints(). The exten collides with no shopphone*/GSM pattern.
                for (mgrId in entry.managerIds) {
                    appendLine("exten => ${config.managerEndpointId(mgrId)},1,Dial(PJSIP/${config.managerEndpointId(mgrId)},45)")
                    appendLine(" same => n,Hangup()")
                }

                // The in-shop device's own context: internal extens + "manager".
                appendLine()
                appendLine("[${config.internalContext(id)}]")
                appendLine("; In-shop device for shop $id — internal calls only, no GSM access.")
                appendLine("exten => manager,1,Dial(PJSIP/${config.endpointId(id)},45)")
                appendLine(" same => n,Hangup()")
                appendLine("include => ${internalIncludeName(id)}")

                // Manager endpoints of SIM-less shops still need a dialable context.
                if (id !in gsmShopIds) {
                    appendLine()
                    appendLine("[${config.outboundContext(id)}]")
                    appendLine("; Manager endpoint for shop $id (no SIM assigned) — internal calls only.")
                    appendLine("include => ${internalIncludeName(id)}")
                }
            }

            // ── Per-manager identity contexts (duty-aware call pool) ──
            // Each manager registers ONE endpoint (mgr{id}) and dials out from here.
            // GSM: the app dials "shop{id}-{number}" so a manager covering several
            // shops picks which SIM to use; the number is handed to that shop's existing
            // outbound context. A manager with exactly one SIM shop may also dial a bare
            // number. Intercom extensions come from the covered shops' internal includes.
            for (entry in managers) {
                appendLine()
                appendLine("[${config.managerContext(entry.managerId)}]")
                appendLine("; Manager ${entry.managerId} — single SIP identity for the call pool.")
                appendLine("; GSM outbound: app dials shop{id}-{number} to select the shop's SIM.")
                appendLine("exten => _shopX.,1,NoOp(mgr${entry.managerId} GSM out ${d}{EXTEN})")
                appendLine(" same => n,Set(REST=${d}{EXTEN:4})")
                appendLine(" same => n,Set(SHOPSEL=${d}{CUT(REST,-,1)})")
                appendLine(" same => n,Set(NUM=${d}{CUT(REST,-,2)})")
                appendLine(" same => n,GotoIf(${d}[\"${d}{NUM}\" = \"\"]?badnum,1)")
                appendLine(" same => n,Goto(${config.outboundContextPrefix}${d}{SHOPSEL},${d}{NUM},1)")
                appendLine("exten => badnum,1,Hangup()")
                // Single-SIM convenience: a bare +45.../0... number uses the only SIM shop.
                val soloGsm = entry.gsmShopIds.singleOrNull()
                if (soloGsm != null) {
                    appendLine("; Single SIM: a bare number routes to shop $soloGsm.")
                    appendLine("exten => _+X.,1,Goto(${config.outboundContext(soloGsm)},${d}{EXTEN},1)")
                    appendLine("exten => _0X.,1,Goto(${config.outboundContext(soloGsm)},${d}{EXTEN},1)")
                }
                // Manager-to-manager intercom: ring a specific colleague's pooled identity.
                // The mgr{id} exten collides with none of the patterns above (shop*/+*/0*)
                // nor the intercom includes (shopphone*/manager); PJSIP/mgr{id} already
                // exists via ensureAllManagerEndpoints().
                for (peerId in entry.peerManagerIds) {
                    val peerEp = config.managerEndpointId(peerId)
                    appendLine("exten => $peerEp,1,Dial(PJSIP/$peerEp,45)")
                    appendLine(" same => n,Hangup()")
                }
                for (shopId in entry.coveredShopIds) {
                    appendLine("include => ${internalIncludeName(shopId)}")
                }
            }
        }
        writeAtomically(file, content)
        if (reload) amiClient.reloadDialplan()
        println("[Asterisk] Wrote $file (${shops.size} GSM + ${internal.size} internal + ${managers.size} manager context set(s))")
    }

    private fun internalIncludeName(shopId: Int) = "internal-shop$shopId"
}

/**
 * One shop's internal-intercom entry. [groupShopIds] = shops whose in-shop device is
 * dialable (itself + shops sharing its primary manager). [managerIds] = every manager
 * covering this shop (primary ∪ pool) — made dialable as mgr{id} so manager-to-manager
 * calls resolve from ANY identity that includes this context.
 */
data class InternalShopEntry(
    val shopId: Int,
    val groupShopIds: List<Int>,
    val managerIds: List<Int> = emptyList(),
)

/**
 * One manager's dial context. [coveredShopIds] = every shop the manager covers (for
 * intercom includes); [gsmShopIds] = the subset of those that currently have a SIM (a
 * single one enables bare-number dialing); [peerManagerIds] = other managers who share
 * at least one covered shop (manager-to-manager intercom targets).
 */
data class ManagerDialEntry(
    val managerId: Int,
    val coveredShopIds: List<Int>,
    val gsmShopIds: List<Int>,
    val peerManagerIds: List<Int> = emptyList(),
)

/**
 * Pure assembly of the dialplan's routing entries from plain DB projections — no IO,
 * so it is unit-testable without Asterisk or a live DB. The provisioner supplies the
 * current shop/manager/pool state; the writer turns the result into dialplan text.
 */
internal object RoutingPlanner {

    /**
     * Intercom groups: each shop paired with every shop sharing its PRIMARY manager
     * (historical grouping — pool membership drives the per-manager contexts, not this).
     * [shops] = (shopId, primaryManagerId).
     */
    fun internalEntries(
        shops: List<Pair<Int, Int>>,
        managersByShop: Map<Int, List<Int>> = emptyMap(),
    ): List<InternalShopEntry> {
        val byManager = shops.groupBy { it.second }
        return shops.map { (shopId, managerId) ->
            val group = byManager[managerId].orEmpty().map { it.first }.ifEmpty { listOf(shopId) }
            InternalShopEntry(shopId, group, managersByShop[shopId].orEmpty())
        }
    }

    /**
     * Per-manager dial entries. [coveredShopsByManager] = managerId → shops the manager
     * covers (primary ∪ pool); [managerIdsByShop] = shopId → managers covering it. Peers =
     * co-managers of any covered shop, deduped and minus self. [gsmShopIds] = shops with a
     * live SIM (a covered SIM shop enables that manager's bare-number dialing).
     */
    fun managerEntries(
        managerIds: List<Int>,
        coveredShopsByManager: Map<Int, List<Int>>,
        managerIdsByShop: Map<Int, List<Int>>,
        gsmShopIds: Set<Int>,
    ): List<ManagerDialEntry> = managerIds.map { mid ->
        val covered = coveredShopsByManager[mid].orEmpty()
        val peers = covered
            .flatMap { managerIdsByShop[it].orEmpty() }
            .filter { it != mid }
            .distinct()
        ManagerDialEntry(
            managerId = mid,
            coveredShopIds = covered,
            gsmShopIds = covered.filter { it in gsmShopIds },
            peerManagerIds = peers,
        )
    }
}
